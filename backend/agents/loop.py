def _tool_schemas(tools: dict[str, Tool]) -> list[dict[str, Any]]:
    """Build an LLM-facing tool schema list from the given allow-list.

    Args:
        tools: Mapping of tool name to :class:`~backend.agents.tools.base.Tool`
            instances (the loop's allow-list).

    Returns:
        A list of ``{"name": ..., "description": ..., "parameters": ...}``
        dicts suitable for passing to :meth:`~backend.llm.base.LLMProvider.chat`.
    """
    return [
        {
            "name": t.name,
            "description": t.description,
            "parameters": t.arguments_schema,
        }
        for t in tools.values()
    ]
